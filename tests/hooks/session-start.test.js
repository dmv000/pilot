// T-H01: session-start (F05, R9).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { tmpProject, runHook, write } from '../helpers.js';

const ctx = r => r.json?.hookSpecificOutput?.additionalContext ?? '';

test('injects HANDOFF for every session source', () => {
  const dir = tmpProject({ files: { 'docs/planning/HANDOFF.md': '# Handoff\nNext action: run /pilot:step 2' } });
  for (const source of ['startup', 'resume', 'clear', 'compact']) {
    const r = runHook('session-start.js', dir, { hook_event_name: 'SessionStart', source });
    assert.equal(r.code, 0);
    assert.match(ctx(r), /run \/pilot:step 2/, source);
  }
});

test('truncates long HANDOFF to stay under 8,000 characters', () => {
  const dir = tmpProject({ files: { 'docs/planning/HANDOFF.md': 'x'.repeat(20000) } });
  const r = runHook('session-start.js', dir, { hook_event_name: 'SessionStart', source: 'startup' });
  assert.ok(ctx(r).length <= 8000, String(ctx(r).length));
  assert.match(ctx(r), /truncated/);
});

test('design reminder only while design is pending and DESIGN.md is absent', () => {
  const dir = tmpProject();
  let r = runHook('session-start.js', dir, { hook_event_name: 'SessionStart', source: 'startup' });
  assert.match(ctx(r), /Design system not created yet/);
  write(dir, 'docs/design/DESIGN.md', '# Design');
  r = runHook('session-start.js', dir, { hook_event_name: 'SessionStart', source: 'startup' });
  assert.doesNotMatch(ctx(r), /Design system not created yet/);
  const dir2 = tmpProject({ manifest: { design: 'not-applicable' } });
  r = runHook('session-start.js', dir2, { hook_event_name: 'SessionStart', source: 'startup' });
  assert.doesNotMatch(ctx(r), /Design system not created yet/);
});

test('reports draft docs, open issue counts and dirty state', () => {
  const dir = tmpProject({ files: {
    'docs/requirements/PRD.md': 'Purpose: x\nRead this when: x\nRelated files: x\n\nStatus: Draft\n',
    'docs/issues/BUGS.md': 'Generated by /pilot:sync from GitHub Issues. Do not edit.\n\n| # | Title | IDs | Opened |\n| --- | --- | --- | --- |\n| #3 | crash | FR-001 | 2026-10-20 |\n| #4 | typo | - | 2026-10-21 |\n',
    '.pilot/state.json': JSON.stringify({ dirty: true })
  } });
  const r = runHook('session-start.js', dir, { hook_event_name: 'SessionStart', source: 'resume' });
  assert.match(ctx(r), /PRD\.md/);
  assert.match(ctx(r), /Open bugs: 2/);
  assert.match(ctx(r), /not yet passed the fast checks/);
});
