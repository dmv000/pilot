#!/usr/bin/env node
// Evidence for /pilot:audit (spec 6.13). Run in the pilot repository.
//
//   node scripts/audit.js                  print the evidence table (markdown) and write docs/audits/<date>-evidence.md
//   node scripts/audit.js --json           same data as JSON
//   node scripts/audit.js record <file>    append one audit decision record (JSON object) to docs/audits/audit-history.jsonl
//
// Pre-registered rules (fixed in P3 section 3; not tuned after seeing data):
//   keep           every mapped eval case has with-plugin score >= 0.8 and delta >= +0.3
//   retire-candidate  every mapped case scores >= 0.8 with AND without the plugin (delta < +0.3): today's model no longer needs it
//   fix            some mapped case scores < 0.8 with the plugin: the component does not do its job
//   enforcement    no eval maps to it, but unit tests or CI checks do: a deterministic guard; keep unless the platform now does the same
//   no-evidence    nothing maps to it, or the evals have never run
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AUDITS = path.join(REPO, 'docs', 'audits');
const read = f => { try { return fs.readFileSync(f, 'utf8'); } catch { return null; } };

export function parseRegistry(text) {
  return text.split('\n').filter(l => /^\|\s*[A-Z]+-[A-Z0-9]+\s*\|/.test(l)).map(l => l.split('|').map(c => c.trim()))
    .map(r => ({ id: r[1], path: r[2].replace(/`/g, ''), purpose: r[3], prevents: r[4], check: r[5], status: r[6], retireWhen: r[7] }));
}

export function latestEvals(historyText) {
  const lines = (historyText ?? '').split('\n').filter(Boolean).map(l => JSON.parse(l));
  return lines.at(-1) ?? null;
}

/** Map a component to eval cases by the E-ids in its check column (E-04a-c expands to E-04a, E-04b, E-04c). */
export function evalIds(check) {
  const ids = [];
  for (const m of (check ?? '').matchAll(/\bE-(\d{2})([a-z])?(?:[–-]([a-z]))?/g)) {
    if (m[2] && m[3]) for (let c = m[2].charCodeAt(0); c <= m[3].charCodeAt(0); c++) ids.push(`E-${m[1]}${String.fromCharCode(c)}`);
    else ids.push(`E-${m[1]}${m[2] ?? ''}`);
  }
  return ids;
}

export function classify(row, evals) {
  const ids = evalIds(row.check);
  const unitTested = /\b[TC]-[A-Za-z0-9-]+|tests\//.test(row.check ?? '');
  if (!ids.length) return { verdict: unitTested ? 'enforcement' : 'no-evidence', cases: [] };
  if (!evals) return { verdict: 'no-evidence', cases: [], note: 'evals have never been recorded (npm run eval)' };
  const cases = evals.cases.filter(c => ids.some(id => c.name === id || c.name.startsWith(`${id}-`)));
  if (!cases.length) return { verdict: 'no-evidence', cases: [], note: `no recorded result for ${ids.join(', ')}` };
  if (cases.some(c => c.score < 0.8)) return { verdict: 'fix', cases };
  if (cases.every(c => typeof c.delta === 'number' && c.delta < 0.3)) return { verdict: 'retire-candidate', cases };
  return { verdict: 'keep', cases };
}

function claudeVersion() {
  const r = spawnSync('claude --version', { encoding: 'utf8', shell: true });
  return r.status === 0 ? r.stdout.trim() : 'unknown';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const [cmd, arg] = process.argv.slice(2).filter(a => a !== '--json');
  if (cmd === 'record') {
    const rec = JSON.parse(read(path.resolve(arg)));
    fs.mkdirSync(AUDITS, { recursive: true });
    fs.appendFileSync(path.join(AUDITS, 'audit-history.jsonl'), JSON.stringify({ at: new Date().toISOString(), ...rec }) + '\n');
    console.log('appended to docs/audits/audit-history.jsonl');
    process.exit(0);
  }
  const rows = parseRegistry(read(path.join(REPO, 'REGISTRY.md')) ?? '');
  const evals = latestEvals(read(path.join(AUDITS, 'eval-history.jsonl')));
  const result = rows.map(r => ({ ...r, ...classify(r, evals) }));
  if (process.argv.includes('--json')) { console.log(JSON.stringify({ claudeVersion: claudeVersion(), evals: evals ? { at: evals.at, claudeVersion: evals.claudeVersion } : null, components: result }, null, 2)); process.exit(0); }
  const fmt = c => c.cases.map(x => `${x.name}: ${x.score.toFixed(2)} (Δ ${typeof x.delta === 'number' ? (x.delta >= 0 ? '+' : '') + x.delta.toFixed(2) : 'n/a'})`).join('; ');
  const lines = [
    `# Audit evidence (${new Date().toISOString().slice(0, 10)})`, '',
    'Purpose: per-component evidence for /pilot:audit, generated by scripts/audit.js.',
    'Read this when: deciding whether a kit component is kept, fixed, merged or retired.',
    'Related files: REGISTRY.md, docs/audits/eval-history.jsonl, docs/audits/audit-history.jsonl', '',
    `Claude Code: ${claudeVersion()}. Latest recorded evals: ${evals ? `${evals.at} (Claude Code ${evals.claudeVersion})` : 'none (run npm run eval)'}.`, '',
    '| ID | Path | Verdict | Evidence | Retire when |', '| --- | --- | --- | --- | --- |',
    ...result.map(r => `| ${r.id} | \`${r.path}\` | ${r.verdict} | ${r.cases.length ? fmt(r) : (r.note ?? r.check)} | ${r.retireWhen} |`), ''
  ];
  fs.mkdirSync(AUDITS, { recursive: true });
  const out = path.join(AUDITS, `${new Date().toISOString().slice(0, 10)}-evidence.md`);
  fs.writeFileSync(out, lines.join('\n'));
  console.log(lines.join('\n'));
  console.log(`\nwritten to ${path.relative(REPO, out)}`);
}
