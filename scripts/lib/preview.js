// Deterministic design preview: tokens.json (+ DESIGN.md title) -> preview.html. Never hand-edit the output.
const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

function flatten(obj, prefix = '') {
  const out = [];
  for (const key of Object.keys(obj).sort()) {
    const v = obj[key];
    if (v && typeof v === 'object' && '$value' in v) out.push([prefix + key, v.$value, v.$type ?? '']);
    else if (v && typeof v === 'object') out.push(...flatten(v, prefix + key + '.'));
    else out.push([prefix + key, v, '']);
  }
  return out;
}

export function renderPreview(tokens, designMd = '') {
  const title = (designMd.match(/^#\s+(.+)$/m)?.[1] ?? 'Design system').trim();
  const rows = flatten(tokens);
  const swatch = ([name, value, type]) => {
    const isColor = type === 'color' || /^#|^rgb|^hsl|^oklch/i.test(String(value));
    const sample = isColor ? `<span class="sw" style="background:${esc(value)}"></span>` : name.startsWith('font') || type === 'fontFamily' || type === 'dimension' && name.includes('font')
      ? `<span style="font:${esc(value)}">Aa</span>` : '';
    return `<tr><td><code>${esc(name)}</code></td><td>${sample}</td><td><code>${esc(typeof value === 'object' ? JSON.stringify(value) : value)}</code></td></tr>`;
  };
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
body{font-family:system-ui,sans-serif;margin:24px;max-width:960px;color:#111;background:#fff}
@media (prefers-color-scheme:dark){body{color:#eee;background:#111}}
table{border-collapse:collapse;width:100%}td,th{border-bottom:1px solid #8884;padding:6px 8px;text-align:left}
.sw{display:inline-block;width:40px;height:20px;border:1px solid #8888;border-radius:4px}
</style>
</head>
<body>
<h1>${esc(title)}</h1>
<p>Generated by pilot from docs/design/tokens.json. Do not edit this file; change tokens.json or DESIGN.md and regenerate.</p>
<table><thead><tr><th>Token</th><th>Sample</th><th>Value</th></tr></thead><tbody>
${rows.map(swatch).join('\n')}
</tbody></table>
</body>
</html>
`;
}
