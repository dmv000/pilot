// Deterministic design preview: tokens.json (+ DESIGN.md title) -> preview.html. Never hand-edit the output.
import { flattenTokens, parseColor, contrast } from './design.js';

const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const show = v => (Array.isArray(v) ? v.join(', ') : typeof v === 'object' ? JSON.stringify(v) : String(v));

export function renderPreview(tokens, designMd = '') {
  const title = (designMd.match(/^#\s+(.+)$/m)?.[1] ?? 'Design system').trim();
  const leaves = flattenTokens(tokens).filter(([, l]) => !('invalid' in l)).sort(([a], [b]) => a.localeCompare(b));
  const byPath = Object.fromEntries(leaves);

  const sample = (name, leaf) => {
    const v = leaf.$value;
    if (leaf.$type === 'color' && parseColor(v)) return `<span class="sw" style="background:${esc(v)}"></span>`;
    if (leaf.$type === 'fontFamily') return `<span style="font-family:${esc(show(v))}">Aa Bb 123</span>`;
    if (leaf.$type === 'dimension' && name.startsWith('font.size')) return `<span style="font-size:${esc(v)}">Aa</span>`;
    if (leaf.$type === 'dimension' && name.startsWith('space.')) return `<span class="bar" style="width:${esc(v)}"></span>`;
    if (leaf.$type === 'dimension' && name.startsWith('radius.')) return `<span class="box" style="border-radius:${esc(v)}"></span>`;
    if (leaf.$type === 'shadow') return `<span class="box" style="box-shadow:${esc(v)}"></span>`;
    return '';
  };
  const rows = leaves.map(([name, leaf]) => `<tr><td><code>${esc(name)}</code></td><td>${sample(name, leaf)}</td><td><code>${esc(show(leaf.$value))}</code></td></tr>`);

  const pairs = (tokens.$pilot?.contrastPairs ?? []).map(({ fg, bg, min = 4.5 }) => {
    const a = parseColor(byPath[fg]?.$value);
    const b = parseColor(byPath[bg]?.$value);
    const ratio = a && b ? contrast(a, b) : 0;
    const ok = ratio + 1e-9 >= min;
    const demo = a && b ? `<span class="pair" style="color:${esc(byPath[fg].$value)};background:${esc(byPath[bg].$value)}">Sample text</span>` : '';
    return `<tr><td><code>${esc(fg)}</code> on <code>${esc(bg)}</code></td><td>${demo}</td><td>${ratio.toFixed(2)}:1 (min ${min}:1)</td><td>${ok ? 'pass' : '<strong>FAIL</strong>'}</td></tr>`;
  });

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
body{font-family:system-ui,sans-serif;margin:24px;max-width:960px;color:#111;background:#fff}
@media (prefers-color-scheme:dark){body{color:#eee;background:#111}}
table{border-collapse:collapse;width:100%;margin-bottom:32px}td,th{border-bottom:1px solid #8884;padding:6px 8px;text-align:left;vertical-align:middle}
.sw{display:inline-block;width:40px;height:20px;border:1px solid #8888;border-radius:4px}
.bar{display:inline-block;height:12px;background:#8888}
.box{display:inline-block;width:40px;height:24px;border:1px solid #8888;background:#fff}
.pair{display:inline-block;padding:4px 10px;border-radius:4px}
</style>
</head>
<body>
<h1>${esc(title)}</h1>
<p>Generated by pilot from docs/design/tokens.json. Do not edit this file; change tokens.json or DESIGN.md and regenerate with <code>pilot.js preview</code>.</p>
<h2>Contrast</h2>
<table><thead><tr><th>Pair</th><th>Sample</th><th>Ratio</th><th>Result</th></tr></thead><tbody>
${pairs.join('\n')}
</tbody></table>
<h2>Tokens</h2>
<table><thead><tr><th>Token</th><th>Sample</th><th>Value</th></tr></thead><tbody>
${rows.join('\n')}
</tbody></table>
</body>
</html>
`;
}
