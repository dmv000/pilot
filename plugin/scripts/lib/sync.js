// Build BUGS.md, PROBLEMS.md and RESOLVED.md from `gh issue list --json` output.
// GitHub Issues is the source of truth; these files are generated mirrors.
const GEN = 'Generated by /pilot:sync from GitHub Issues. Do not edit.';

const header = (what, related) =>
  `${GEN}\n\nPurpose: mirror of ${what} for cheap reading.\nRead this when: you need the list of ${what}.\nRelated files: ${related}\n\n`;

const ids = body => [...new Set((body ?? '').match(/\b(?:US|FR|NFR)-\d{3,}\b/g) ?? [])].join(', ') || '-';
const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const section = (body, name) => {
  const m = (body ?? '').match(new RegExp(`###\\s*${name}[^\\n]*\\n+([\\s\\S]*?)(?=\\n###\\s|$)`, 'i'));
  const v = m ? m[1].trim() : '';
  return v && !/^_?no response_?$/i.test(v) ? v : '-';
};
const hasLabel = (issue, name) => (issue.labels ?? []).some(l => (l.name ?? l) === name);
const day = s => (s ?? '').slice(0, 10) || '-';

// Issues resolved while the project kept issues locally live under this heading in RESOLVED.md.
// They never existed on GitHub, so a sync keeps them instead of regenerating them away.
export const LOCAL_RESOLVED = '## Resolved without GitHub';

export function buildMirrors(issues, previousResolved = '') {
  const open = issues.filter(i => (i.state ?? '').toUpperCase() === 'OPEN');
  const closed = issues.filter(i => (i.state ?? '').toUpperCase() === 'CLOSED');
  const byNum = (a, b) => a.number - b.number;
  const table = list => '| # | Title | IDs | Opened |\n| --- | --- | --- | --- |\n' +
    list.sort(byNum).map(i => `| #${i.number} | ${cell(i.title)} | ${ids(i.body)} | ${day(i.createdAt)} |`).join('\n') + (list.length ? '\n' : '');
  const bugs = header('open bugs', '.github/ISSUE_TEMPLATE/bug.yml, docs/issues/RESOLVED.md') + table(open.filter(i => hasLabel(i, 'bug')));
  const problems = header('open problems', '.github/ISSUE_TEMPLATE/problem.yml') + table(open.filter(i => hasLabel(i, 'problem')));
  const resolved = header('resolved bugs and problems', 'docs/issues/BUGS.md, docs/LESSONS.md') +
    '| # | Title | Root cause | Regression test | Closed |\n| --- | --- | --- | --- | --- |\n' +
    closed.filter(i => hasLabel(i, 'bug') || hasLabel(i, 'problem')).sort(byNum)
      .map(i => `| #${i.number} | ${cell(i.title)} | ${cell(section(i.body, 'Root cause'))} | ${cell(section(i.body, 'Regression test'))} | ${day(i.closedAt)} |`).join('\n') + '\n';
  const at = (previousResolved ?? '').indexOf(LOCAL_RESOLVED);
  const kept = at === -1 ? '' : '\n' + previousResolved.slice(at).trimEnd() + '\n';
  return { 'docs/issues/BUGS.md': bugs, 'docs/issues/PROBLEMS.md': problems, 'docs/issues/RESOLVED.md': resolved + kept };
}

/** Remove PENDING.md rows whose LOCAL id now appears in an issue body ("pilot-local-id: LOCAL-001"). */
export function prunePending(pendingText, issues) {
  if (!pendingText) return pendingText;
  const filed = new Set(issues.flatMap(i => (i.body ?? '').match(/pilot-local-id:\s*(LOCAL-\d+)/g) ?? []).map(s => s.split(/:\s*/)[1]));
  return pendingText.split('\n').filter(line => {
    const m = line.match(/^\|\s*(LOCAL-\d+)\s*\|/);
    return !(m && filed.has(m[1]));
  }).join('\n');
}
